// Web konsolu tarayıcı E2E testi (Playwright/Chromium). Kullanım: node tests/e2e/web_console.js http://127.0.0.1:8077
const { chromium } = require('playwright');
(async () => {
  const base = process.argv[2] || 'http://127.0.0.1:8077';
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const problems = [];
  page.on('console', (m) => { if (['error', 'warning'].includes(m.type()) && !/favicon|404/.test(m.text())) problems.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', (e) => problems.push('pageerror: ' + e.message));
  const results = {};
  const ok = (k, v) => { results[k] = !!v; console.log((v ? 'OK   ' : 'FAIL ') + k); };
  await page.goto(base);
  ok('login screen visible', await page.locator('#loginForm').isVisible());
  await page.fill('#email', `web_${Date.now()}@example.com`);
  await page.fill('#password', 'Passw0rd!webtest');
  await page.click('#regBtn');
  await page.waitForSelector('#app:not([hidden])', { timeout: 15000 });
  await page.waitForFunction(() => document.querySelectorAll('#stats .stat').length >= 8, null, { timeout: 15000 });
  ok('registered + dashboard', true);
  await page.fill('#topic', 'Tarayıcı testi: gezegenlerin sırası');
  await page.fill('#duration', '15');
  await page.selectOption('#mode', 'slideshow');
  await page.selectOption('#tier', 'draft');
  await page.click('#estBtn');
  await page.waitForFunction(() => document.getElementById('estimate').textContent.includes('Tahmini maliyet'), null, { timeout: 15000 });
  ok('estimate shown', true);
  await page.click('#createBtn');
  await page.waitForSelector('#detail:not([hidden])', { timeout: 20000 });
  ok('job created + detail', true);
  await page.waitForFunction(() => document.querySelector('#detail .pill')?.textContent.includes('İnceleme gerekli'), null, { timeout: 240000, polling: 1000 });
  ok('reached NEEDS_REVIEW (offline content never auto-publishes)', true);
  const qc = await page.locator('#detail h3').innerText();
  ok('QC score shown', /Kalite \d+\/100/.test(qc));
  await page.waitForSelector('#detail video');
  const dur = await page.evaluate(() => new Promise((res) => { const v = document.querySelector('#detail video'); const t = setTimeout(() => res(0), 15000); v.addEventListener('loadedmetadata', () => { clearTimeout(t); res(v.duration); }); if (v.readyState >= 1) { clearTimeout(t); res(v.duration); } }));
  ok('video metadata loads in browser (' + dur.toFixed(1) + 's)', dur > 5);
  ok('no console errors / CSP violations', problems.length === 0);
  if (problems.length) console.log(problems.join('\n'));
  await page.screenshot({ path: process.env.SHOT || '/tmp/web_console.png', fullPage: false });
  await browser.close();
  const failed = Object.entries(results).filter(([, v]) => !v).map(([k]) => k);
  console.log(failed.length ? 'BAŞARISIZ: ' + failed : 'TÜMÜ GEÇTİ (' + Object.keys(results).length + ')');
  process.exit(failed.length ? 1 : 0);
})();
